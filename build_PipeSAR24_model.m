function setMFB(blockPath, script, paramNames)
% 写入 MATLAB Function 块代码，并把指定输入参数的作用域改为 Parameter
% （Parameter 作用域的数据会自动从 base workspace 解析同名变量）
rt = sfroot;
ch = rt.find('-isa','Stateflow.EMChart','Path',blockPath);
if isempty(ch)
    error('找不到 MATLAB Function 块: %s', blockPath);
end
ch = ch(1);
ch.Script = script;
for kk = 1:numel(paramNames)
    d = ch.find('-isa','Stateflow.Data','Name',paramNames{kk});
    if isempty(d)
        error('块 %s 中找不到数据 %s', blockPath, paramNames{kk});
    end
    d(1).Scope = 'Parameter';
end
end

function s = sarScriptR(stg, Nb)
% 生成带冗余的 SAR 级代码（对应 SAR_FUN_R：N 位全部开关，余差含末位反馈）
% 每个仿真步对当前采样值完成一次完整 N 位 SAR 转换（行为级，Vcm-Based 时序）
s = sprintf([ ...
'function [D%d, Vresp%d, Vresn%d] = fcn(Vip0, Vin0, Vref%d, C_act_p%d, C_act_n%d, C_tot_p%d, C_tot_n%d, Vn_sig_p%d, Vn_sig_n%d, Comp_offset%d, Comp_noise)\n' ...
'%%#codegen\n' ...
'%% 第 %d 级 SAR（%d bit，带冗余，移植自 SAR_FUN_R，Vcm-Based 时序）\n' ...
'Vip = Vip0 + Vn_sig_p%d*randn;   %% kT/C 采样噪声\n' ...
'Vin = Vin0 + Vn_sig_n%d*randn;\n' ...
'D%d = zeros(1,%d);\n' ...
'for i = 1:%d\n' ...
'    if Vip - Vin <= Comp_offset%d + Comp_noise*randn\n' ...
'        D%d(i) = 0;\n' ...
'        Vip = Vip + Vref%d/2*C_act_p%d(i)/C_tot_p%d;\n' ...
'        Vin = Vin - Vref%d/2*C_act_n%d(i)/C_tot_n%d;\n' ...
'    else\n' ...
'        D%d(i) = 1;\n' ...
'        Vip = Vip - Vref%d/2*C_act_p%d(i)/C_tot_p%d;\n' ...
'        Vin = Vin + Vref%d/2*C_act_n%d(i)/C_tot_n%d;\n' ...
'    end\n' ...
'end\n' ...
'Vresp%d = Vip;   %% 转换完成后的余差电压（送级间放大器）\n' ...
'Vresn%d = Vin;\n'], ...
stg,stg,stg, stg,stg,stg,stg,stg,stg,stg,stg, ...
stg,Nb, stg,stg, stg,Nb, Nb, stg, ...
stg, stg,stg,stg, stg,stg,stg, ...
stg, stg,stg,stg, stg,stg,stg, ...
stg,stg);
end

function s = sarScriptLast(stg, Nb)
% 生成末级 SAR 代码（对应 SAR_FUN：前 N-1 位开关，最后一位仅比较）
s = sprintf([ ...
'function D%d = fcn(Vip0, Vin0, Vref%d, C_act_p%d, C_act_n%d, C_tot_p%d, C_tot_n%d, Vn_sig_p%d, Vn_sig_n%d, Comp_offset%d, Comp_noise)\n' ...
'%%#codegen\n' ...
'%% 第 %d 级 SAR（%d bit，末级，移植自 SAR_FUN，最后一位不开关）\n' ...
'Vip = Vip0 + Vn_sig_p%d*randn;\n' ...
'Vin = Vin0 + Vn_sig_n%d*randn;\n' ...
'D%d = zeros(1,%d);\n' ...
'for i = 1:%d\n' ...
'    if Vip - Vin <= Comp_offset%d + Comp_noise*randn\n' ...
'        D%d(i) = 0;\n' ...
'        Vip = Vip + Vref%d/2*C_act_p%d(i)/C_tot_p%d;\n' ...
'        Vin = Vin - Vref%d/2*C_act_n%d(i)/C_tot_n%d;\n' ...
'    else\n' ...
'        D%d(i) = 1;\n' ...
'        Vip = Vip - Vref%d/2*C_act_p%d(i)/C_tot_p%d;\n' ...
'        Vin = Vin + Vref%d/2*C_act_n%d(i)/C_tot_n%d;\n' ...
'    end\n' ...
'end\n' ...
'if Vip - Vin <= Comp_offset%d + Comp_noise*randn\n' ...
'    D%d(%d) = 0;\n' ...
'else\n' ...
'    D%d(%d) = 1;\n' ...
'end\n'], ...
stg,stg,stg,stg,stg,stg,stg,stg,stg, ...
stg,Nb, stg,stg, stg,Nb, Nb-1, stg, ...
stg, stg,stg,stg, stg,stg,stg, ...
stg, stg,stg,stg, stg,stg,stg, ...
stg, stg,Nb, stg,Nb);
end

function s = raScript(stg)
% 生成级间余差放大器代码（移植自 RA_FUN，含有限增益/有限带宽/失调/噪声）
s = sprintf([ ...
'function [Voutp%d, Voutn%d] = fcn(Vip, Vin, Av, GBW, Cs%d, Ch%d, Vcm, Amp_offset, Amp_noise, fs)\n' ...
'%%#codegen\n' ...
'%% 第 %d 个级间余差放大器（移植自 RA_FUN）\n' ...
'Av_abs = 10^(Av/20);                %% 开环增益绝对值\n' ...
'beta   = Cs%d/Ch%d;                  %% 反馈系数，闭环增益约 1/beta\n' ...
'tamp   = 0.4/fs;                    %% 放大建立时间\n' ...
'toi    = 1/(2*pi*beta*GBW);         %% 闭环时间常数\n' ...
'g = (Av_abs/(1+beta*Av_abs))*(1-exp(-tamp/toi));  %% 含静态+动态误差的实际增益\n' ...
'Voutp%d = Vcm + g*(Vip - Vcm + Amp_offset + Amp_noise*randn);\n' ...
'Voutn%d = Vcm + g*(Vin - Vcm);\n'], ...
stg,stg,stg,stg, stg, stg,stg, stg,stg);
end

function s = calScript()
% 数字后端默认代码：理想权重重组（= 原脚本的 DOUT1+DOUT2+DOUT3-OFS）
% ====== 这里就是预留给你的数字校准算法的接口 ======
s = sprintf([ ...
'function [Dout, Vout] = fcn(D1, D2, D3, W1, W2, W3, OFS, Kv)\n' ...
'%%#codegen\n' ...
'%% ================= 数字校准接口 =================\n' ...
'%% 输入:  D1 [1xN1]  第一级原始码 (MSB first)\n' ...
'%%        D2 [1xN2]  第二级原始码\n' ...
'%%        D3 [1xN3]  第三级原始码\n' ...
'%% 参数:  W1/W2/W3   各级位权 (默认理想二进制权重, 可由校准算法更新)\n' ...
'%%        OFS        失调修正项, Kv = Vref1/2^N\n' ...
'%% 输出:  Dout 校准后的数字码, Vout 折算电压\n' ...
'%%\n' ...
'%% >>> 在此处替换/插入你的数字校准算法 <<<\n' ...
'%% 默认实现: 理想重组 (与 PipeSAR_test_3stage.m 一致)\n' ...
'Dout = D1*W1(:) + D2*W2(:) + D3*W3(:) - OFS;\n' ...
'Vout = Dout*Kv;\n']);
end
